using System.Diagnostics;
using System.Runtime.Versioning;
using Typlo.App.Platform.Shared;
using Typlo.Core.Hotkeys;
using static Typlo.App.Platform.Mac.ObjC;

namespace Typlo.App.Platform.Mac;

/// <summary>
/// macOS: NSPasteboard (polled via changeCount), NSWorkspace for the frontmost app,
/// a LaunchAgent for autostart and <c>caffeinate</c> for keep-awake.
/// Hotkeys and synthetic input need the Accessibility permission (System Settings → Privacy).
/// </summary>
[SupportedOSPlatform("macos")]
public sealed class MacPlatform : HookPlatformBase
{
    private const string TypeText = "public.utf8-plain-text";
    private const string TypePng = "public.png";
    private const string TypeTiff = "public.tiff";
    private const string TypeHtml = "public.html";
    private const string TypeRtf = "public.rtf";
    private const string TypeFileUrl = "public.file-url";
    // Legacy type that still returns every copied file as a plist array of paths.
    private const string TypeFilenames = "NSFilenamesPboardType";
    // nspasteboard.org conventions used by password managers and screenshot tools.
    private static readonly string[] SkipTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];
    private const string AgentLabel = "pro.typlo.app";

    private readonly Lock _pbLock = new();
    private Process? _caffeinate;

    public MacPlatform()
    {
        if (!AXIsProcessTrusted())
        {
            Log.Error("Accessibility permission missing: hotkeys and paste will not work until granted.");
            try { Process.Start("open", "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility"); }
            catch (Exception) { }
        }
        StartClipboardMonitor();
    }

    public override string Name => "macOS";

    public override PlatformCapabilities Capabilities => new(
        GlobalHotkeys: true, SimulateInput: true, SwitchLayout: false, DetectHotkeyConflicts: false,
        Notes: AXIsProcessTrusted() ? null
            : Services.Loc.T("note.mac.ax"));

    protected override KeyModifiers ShortcutModifier => KeyModifiers.Win; // Cmd
    protected override TimeSpan PollInterval => TimeSpan.FromMilliseconds(300);

    private static nint Pasteboard => Call(Class("NSPasteboard"), "generalPasteboard");

    protected override ulong ReadChangeToken()
    {
        lock (_pbLock) return Pool(() => (ulong)(long)Call(Pasteboard, "changeCount"));
    }

    protected override RawClip? ReadClip()
    {
        lock (_pbLock) return Pool(() =>
        {
            var pb = Pasteboard;
            var types = ToStringList(Call(pb, "types"));
            if (types.Any(SkipTypes.Contains)) return null;
            var app = FrontmostAppName();
            if (types.Contains(TypeFileUrl) && ToStringList(Call(pb, "propertyListForType:", NSString(TypeFilenames))) is { Count: > 0 } files)
                return new RawClip(null, null, false, app, Files: files);
            if (types.Contains(TypeText) && ToStr(Call(pb, "stringForType:", NSString(TypeText))) is { Length: > 0 } text)
            {
                var html = types.Contains(TypeHtml) && ToBytes(Call(pb, "dataForType:", NSString(TypeHtml))) is { Length: > 0 } h
                    ? System.Text.Encoding.UTF8.GetString(h) : null;
                var rtf = types.Contains(TypeRtf) && ToBytes(Call(pb, "dataForType:", NSString(TypeRtf))) is { Length: > 0 } r
                    ? System.Text.Encoding.Latin1.GetString(r) : null;
                return new RawClip(text, null, false, app, html, rtf);
            }
            if (types.Contains(TypePng) && ToBytes(Call(pb, "dataForType:", NSString(TypePng))) is { Length: > 0 } png)
                return new RawClip(null, png, true, app);
            if (types.Contains(TypeTiff) && TiffToPng(Call(pb, "dataForType:", NSString(TypeTiff))) is { Length: > 0 } converted)
                return new RawClip(null, converted, true, app);
            return (RawClip?)null;
        });
    }

    /// <summary>Skia cannot decode TIFF, so convert through NSBitmapImageRep.</summary>
    private static byte[]? TiffToPng(nint tiff)
    {
        if (tiff == 0) return null;
        var rep = Call(Class("NSBitmapImageRep"), "imageRepWithData:", tiff);
        if (rep == 0) return null;
        var props = Call(Class("NSDictionary"), "dictionary");
        const long NSBitmapImageFileTypePNG = 4;
        var data = Send(rep, Sel("representationUsingType:properties:"), (nint)NSBitmapImageFileTypePNG, props);
        return ToBytes(data);
    }

    public override string? ReadText()
    {
        lock (_pbLock) return Pool(() => ToStr(Call(Pasteboard, "stringForType:", NSString(TypeText))));
    }

    protected override void WriteText(string text)
    {
        lock (_pbLock) Pool(() =>
        {
            var pb = Pasteboard;
            Call(pb, "clearContents");
            Call(pb, "setString:forType:", NSString(text), NSString(TypeText));
            return 0;
        });
    }

    protected override void WriteRichText(string text, string? html, string? rtf)
    {
        lock (_pbLock) Pool(() =>
        {
            var pb = Pasteboard;
            Call(pb, "clearContents");
            Call(pb, "setString:forType:", NSString(text), NSString(TypeText));
            if (!string.IsNullOrEmpty(html)) Call(pb, "setData:forType:", NSData(System.Text.Encoding.UTF8.GetBytes(html)), NSString(TypeHtml));
            if (!string.IsNullOrEmpty(rtf)) Call(pb, "setData:forType:", NSData(System.Text.Encoding.Latin1.GetBytes(rtf)), NSString(TypeRtf));
            return 0;
        });
    }

    protected override void WriteFiles(IReadOnlyList<string> paths)
    {
        lock (_pbLock) Pool(() =>
        {
            var pb = Pasteboard;
            var array = Call(Class("NSMutableArray"), "array");
            foreach (var path in paths) Call(array, "addObject:", NSString(path));
            Call(pb, "clearContents");
            Call(pb, "setPropertyList:forType:", array, NSString(TypeFilenames));
            return 0;
        });
    }

    protected override void WriteImage(byte[] png, byte[] bgra, int width, int height)
    {
        lock (_pbLock) Pool(() =>
        {
            var pb = Pasteboard;
            Call(pb, "clearContents");
            Call(pb, "setData:forType:", NSData(png), NSString(TypePng));
            return 0;
        });
    }

    protected override ClipboardSnapshot ReadSnapshot()
    {
        lock (_pbLock) return Pool(() =>
        {
            var pb = Pasteboard;
            var list = new List<(string, byte[])>();
            foreach (var type in ToStringList(Call(pb, "types")))
                if (ToBytes(Call(pb, "dataForType:", NSString(type))) is { } data) list.Add((type, data));
            return new ClipboardSnapshot(list);
        });
    }

    protected override void WriteSnapshot(ClipboardSnapshot snapshot)
    {
        lock (_pbLock) Pool(() =>
        {
            var pb = Pasteboard;
            Call(pb, "clearContents");
            foreach (var (type, data) in snapshot.Formats)
                Call(pb, "setData:forType:", NSData(data), NSString(type));
            return 0;
        });
    }

    // ---------------------------------------------------------------- apps

    private static nint FrontmostApp() => Call(Call(Class("NSWorkspace"), "sharedWorkspace"), "frontmostApplication");

    private static string? FrontmostAppName() => ToStr(Call(FrontmostApp(), "localizedName"));

    /// <summary>On macOS the "window" handle is the frontmost application's PID.</summary>
    public override nint ForegroundWindow => Pool(() =>
    {
        var app = FrontmostApp();
        return app == 0 ? 0 : (nint)(int)Call(app, "processIdentifier");
    });

    public override void ActivateWindow(nint handle)
    {
        if (handle == 0) return;
        Pool(() =>
        {
            var app = SendIntInt(Class("NSRunningApplication"), Sel("runningApplicationWithProcessIdentifier:"), (int)handle);
            const ulong NSApplicationActivateIgnoringOtherApps = 2;
            if (app != 0) SendUL(app, Sel("activateWithOptions:"), (nuint)NSApplicationActivateIgnoringOtherApps);
            return 0;
        });
    }

    // Input sources via TIS need CoreFoundation dictionaries; not wired up yet.
    public override bool SwitchKeyboardLayout(nint window, int langId) => false;

    // ---------------------------------------------------------------- system

    public override bool SetKeepAwake(bool enabled)
    {
        Proc.Stop(ref _caffeinate);
        if (!enabled) return true;
        // -d display, -i idle sleep; -w ties it to our lifetime even if we crash.
        _caffeinate = Proc.Start("/usr/bin/caffeinate", "-d", "-i", "-w", Environment.ProcessId.ToString());
        return _caffeinate is not null;
    }

    // "caffeinate -u" declares the user active, resetting the HID idle time that presence apps read.
    public override void SignalUserActivity() => Proc.Start("/usr/bin/caffeinate", "-u", "-t", "2")?.Dispose();

    private static string AgentPath => Path.Combine(
        Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), "Library", "LaunchAgents", AgentLabel + ".plist");

    public override bool AutostartEnabled
    {
        get => File.Exists(AgentPath);
        set
        {
            if (!value) { if (File.Exists(AgentPath)) File.Delete(AgentPath); return; }
            Directory.CreateDirectory(Path.GetDirectoryName(AgentPath)!);
            var exe = System.Security.SecurityElement.Escape(Environment.ProcessPath ?? "");
            File.WriteAllText(AgentPath, $"""
                <?xml version="1.0" encoding="UTF-8"?>
                <!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
                <plist version="1.0">
                <dict>
                  <key>Label</key><string>{AgentLabel}</string>
                  <key>ProgramArguments</key><array><string>{exe}</string><string>--tray</string></array>
                  <key>RunAtLoad</key><true/>
                  <key>ProcessType</key><string>Interactive</string>
                </dict>
                </plist>
                """);
        }
    }

    public override void Dispose()
    {
        Proc.Stop(ref _caffeinate);
        base.Dispose();
    }
}
